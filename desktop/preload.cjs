const { contextBridge, ipcRenderer } = require("electron");
const call = (channel, ...args) => ipcRenderer.invoke(`aem:${channel}`, ...args);
// Explicit capabilities only. No arbitrary paths, shell commands, Node primitives or IPC channel names.
contextBridge.exposeInMainWorld("aemDesktop", Object.freeze({
  getState: () => call("state"),
  getDiagnostics: () => call("diagnostics"),
  configure: (settings) => call("configure", settings),
  setup: (consent) => call("setup", consent),
  start: () => call("start"),
  stop: () => call("stop"),
  listApps: () => call("apps"),
  launchApp: (pkg) => call("launch", pkg),
  uninstallApp: (pkg) => call("uninstall", pkg),
  clearAppData: (pkg) => call("clear-data", pkg),
  getPermissions: (pkg) => call("permissions", pkg),
  setPermission: (pkg, permission, granted) => call("set-permission", pkg, permission, granted),
  openAndroidSettings: (pkg) => call("android-settings", pkg),
  chooseApk: () => call("choose-apk"),
  installSelectedApk: (token) => call("install-selected", token),
  installCatalogApk: (artifact) => call("install-catalog", artifact),
  chooseFile: () => call("choose-file"),
  pushFile: (token) => call("push-file", token),
  listFiles: () => call("files"),
  pullFile: (remote) => call("pull-file", remote),
  getStorage: () => call("storage"),
  reversePort: (port) => call("reverse-port", port),
  resetDevice: () => call("reset-device"),
  openLogs: () => call("open-logs"),
  exportDiagnostics: () => call("export-diagnostics"),
  getAppInfo: () => call("app-info"),
  checkForUpdates: () => call("check-updates"),
  openExternal: (url) => call("open-external", url),
  onState: (listener) => { const wrapped = (_event, state) => listener(state); ipcRenderer.on("aem:state", wrapped); return () => ipcRenderer.removeListener("aem:state", wrapped); },
  onOpenAndroid: (listener) => { const wrapped = () => listener(); ipcRenderer.on("aem:open-android", wrapped); return () => ipcRenderer.removeListener("aem:open-android", wrapped); },
}));
