create or replace function public.claim_android_artifacts(claim_limit integer default 25)
returns setof public.artifacts language plpgsql security definer set search_path=public as $$
declare claimed_ids bigint[];
begin
  if claim_limit is null or claim_limit<1 or claim_limit>25 then raise exception 'claim_limit must be between 1 and 25'; end if;
  with picked as (
    select id from public.artifacts where platform='android' and kind='apk' and signing_status='pending'
    order by id desc for update skip locked limit claim_limit
  ), changed as (
    update public.artifacts a set signing_status='processing' from picked where a.id=picked.id returning a.id
  ) select coalesce(array_agg(id),'{}'::bigint[]) into claimed_ids from changed;
  if coalesce(array_length(claimed_ids,1),0)=0 then return; end if;
  return query select a.* from public.artifacts a where a.id=any(claimed_ids) order by a.id desc;
end $$;
revoke all on function public.claim_android_artifacts(integer) from public,anon,authenticated;
grant execute on function public.claim_android_artifacts(integer) to service_role;

create or replace function public.aem_trigger_android_signing()
returns trigger language plpgsql security definer set search_path=pg_catalog,public,vault,extensions as $$
declare project_url text; publishable_key text; sync_secret text;
begin
  if new.platform<>'android' or new.kind<>'apk' or new.signing_status<>'pending' then return new; end if;
  if tg_op='UPDATE' then
    if old.signing_status is not distinct from new.signing_status then return new; end if;
  end if;
  select decrypted_secret into project_url from vault.decrypted_secrets where name='aem_project_url' limit 1;
  select decrypted_secret into publishable_key from vault.decrypted_secrets where name='aem_publishable_key' limit 1;
  select decrypted_secret into sync_secret from vault.decrypted_secrets where name='aem_sync_secret' limit 1;
  if coalesce(project_url,'')='' or coalesce(publishable_key,'')='' or coalesce(sync_secret,'')='' then
    raise warning 'Signing dispatch not configured; scheduled worker remains the fallback'; return new;
  end if;
  perform net.http_post(
    url:=project_url||'/functions/v1/aem-trigger-android-signing',
    headers:=jsonb_build_object('Content-Type','application/json','apikey',publishable_key,'x-aem-sync-secret',sync_secret),
    body:=jsonb_build_object('source','database-trigger','artifact_id',new.id,'occurred_at',now()),
    timeout_milliseconds:=10000
  );
  return new;
end $$;
revoke execute on function public.aem_trigger_android_signing() from public,anon,authenticated;
create trigger aem_android_artifact_signing_trigger after insert or update of signing_status on public.artifacts
  for each row execute function public.aem_trigger_android_signing();

