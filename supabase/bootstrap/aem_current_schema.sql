create table public.applications (
  id bigint generated by default as identity primary key,
  provider text not null,
  project text not null,
  package_identity text,
  name text not null,
  description text,
  source_url text,
  icon_url text,
  platforms text[] not null default '{}',
  category text not null default 'Other',
  functionality text[] not null default '{}',
  screenshots text[] not null default '{}',
  permissions text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  rollback_release_id bigint,
  source_external_id text,
  source_visibility text,
  description_source text not null default 'source',
  icon_source text
);
create unique index applications_provider_project_key on public.applications(provider,project);
create unique index applications_provider_external_id_key on public.applications(provider,source_external_id) where source_external_id is not null;

create table public.releases (
  id bigint generated by default as identity primary key,
  application_id bigint not null references public.applications(id) on delete cascade,
  source_release_id text not null,
  version_name text not null,
  version_code bigint,
  channel text not null default 'stable' check (channel in ('stable','beta','development')),
  status text not null default 'published' check (status in ('draft','published','withdrawn')),
  title text,
  notes text,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  unique(application_id,source_release_id)
);
create index releases_application_idx on public.releases(application_id);

alter table public.applications add constraint applications_rollback_release_id_fkey
