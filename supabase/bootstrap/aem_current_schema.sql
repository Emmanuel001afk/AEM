-- Keep a 100 MiB safety margin under the user's 1 GiB Storage quota. The
-- trigger rejects new/replacement objects before the total crosses 900 MiB.
create or replace function public.aem_enforce_artifact_storage_budget()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  used_bytes bigint;
  incoming_bytes bigint;
begin
  if new.bucket_id <> 'aem-artifacts' then return new; end if;
  incoming_bytes := coalesce(nullif(new.metadata->>'size','')::bigint, 0);
  if tg_op = 'UPDATE' then
    select coalesce(sum(coalesce(nullif(metadata->>'size','')::bigint,0)),0)
      into used_bytes from storage.objects
     where bucket_id = 'aem-artifacts' and id <> old.id;
  else
    select coalesce(sum(coalesce(nullif(metadata->>'size','')::bigint,0)),0)
      into used_bytes from storage.objects where bucket_id = 'aem-artifacts';
  end if;
  if used_bytes + incoming_bytes > 900 * 1024 * 1024 then
    raise exception 'AEM artifact storage budget reached (900 MiB safety cap)';
  end if;
  return new;
end;
$$;
revoke all on function public.aem_enforce_artifact_storage_budget() from public, anon, authenticated;
drop trigger if exists aem_artifact_storage_budget on storage.objects;
create trigger aem_artifact_storage_budget
before insert or update on storage.objects
for each row execute function public.aem_enforce_artifact_storage_budget();

